#!/usr/bin/env bash
# Copies the app's own pages into the website as the browser version. The pages
# are the same files the Windows app runs: they look for the desktop bridge and,
# not finding it, fall back to what a browser can do. One source, two builds.
set -euo pipefail
SRC=${1:?usage: build-web.sh <classtools_app dir> <site public dir>}
OUT=${2:?usage: build-web.sh <classtools_app dir> <site public dir>}/classtools
mkdir -p "$OUT/lib" "$OUT/shapes"
cp "$SRC/pdf.html"      "$OUT/presenter.html"
cp "$SRC/calc.html"     "$OUT/calc.html"
cp "$SRC/timer.html"    "$OUT/timer.html"
cp "$SRC/colourpop.js"  "$OUT/colourpop.js"
cp "$SRC"/lib/*         "$OUT/lib/"
cp -r "$SRC"/shapes/*   "$OUT/shapes/"

# The service worker: a short precache of the things every visit needs, and
# cache-first for anything else once it has been fetched, so a lesson carries on
# if the wifi does not. The stamp changes on every build, which retires the old cache.
STAMP=$(date -u +%Y%m%d-%H%M%S)
cat > "$OUT/sw.js" <<JS
/* generated by tools/build-web.sh - do not edit by hand */
const CACHE = 'classtools-$STAMP';
const CORE = ['./', './index.html', './presenter.html', './calc.html', './timer.html',
  './colourpop.js', './manifest.webmanifest', './icon-192.png', './icon-512.png',
  './lib/pdf.min.js', './lib/pdf.worker.min.js', './lib/pdf-lib.min.js'];
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const r = e.request;
  if (r.method !== 'GET' || new URL(r.url).origin !== location.origin) return;
  e.respondWith(caches.match(r).then(hit => hit || fetch(r).then(res => {
    if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(r, copy)); }
    return res;
  }).catch(() => hit)));
});
JS

echo "web build -> $OUT  (sw stamp $STAMP)"
ls -1 "$OUT"
